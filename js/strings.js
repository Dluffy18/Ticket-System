export function t(key, params) {
  let s = tables[lang][key] ?? en[key];
  if (s === undefined) { console.warn('Missing string', key); return key; }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
  return s;
}

// Picks the singular key when n === 1 and the key exists.
export function tn(key, n, params = {}) {
  const k1 = key + '1';
  if (n === 1 && en[k1]) return t(k1, { n, ...params });
  return t(key, { n, ...params });
}
